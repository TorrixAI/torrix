import type { Events, Run, RunData } from "../core/domain";

export function makeEvent(runId: string, type: Events["type"], message: string): Events {
  return { id: crypto.randomUUID(), run_id: runId, message, type, created_at: new Date().toISOString() };
}

export function buildRunRow(d: RunData): Run {
  return {
    id: d.id,
    user_id: d.user_id,
    project_id: d.project_id,
    name: d.name ?? null,
    provider: d.provider ?? null,
    model: d.model ?? null,
    input_tokens: d.input_tokens ?? null,
    output_tokens: d.output_tokens ?? null,
    thinking_tokens: d.thinking_tokens ?? null,
    cache_read_tokens: d.cache_read_tokens ?? null,
    cache_creation_tokens: d.cache_creation_tokens ?? null,
    cost_usd: d.cost_usd ?? null,
    latency_ms: d.latency_ms ?? null,
    status: d.status ?? null,
    finish_reason: d.finish_reason ?? null,
    source: d.source,
    is_golden: d.is_golden ? 1 : 0,
    score: d.score ?? null,
    score_note: null,
    scored_at: null,
    run_note: d.run_note ?? null,
    request_body: d.request_body ?? null,
    request_bytes: d.request_bytes ?? null,
    response_bytes: d.response_bytes ?? null,
    target_url: d.target_url ?? null,
    trace_id: d.trace_id ?? d.id,
    session_id: d.session_id ?? null,
    parent_run_id: d.parent_run_id ?? null,
    routed_from: d.routed_from ?? null,
    fallback_used: d.fallback_used ? 1 : 0,
    structured_output: d.structured_output ?? null,
    json_parse_ok: d.json_parse_ok === true ? 1 : d.json_parse_ok === false ? 0 : null,
    agent_name: d.agent_name ?? null,
    agent_id: d.agent_id ?? null,
    end_user_id: d.end_user_id ?? null,
    prompt_hash: d.prompt_hash ?? null,
    tags: d.tags ? JSON.stringify(d.tags) : null,
    api_key_id: d.api_key_id ?? null,
    dataset_id: d.dataset_id ?? null,
    dataset_row_id: d.dataset_row_id ?? null,
    share_token: d.share_token ?? null,
    is_anomaly: d.is_anomaly ? 1 : 0,
    original_input_tokens: d.original_input_tokens ?? null,
    original_request_body: d.original_request_body ?? null,
    is_seed: 0,
    error: d.error ?? null,
    review_state: d.review_state ?? null,
    pii_masked: d.pii_masked ? 1 : 0,
    pii_findings: d.pii_findings ?? null,
    policy_flags: d.policy_flags ?? null,
    share_expires_at: d.share_expires_at ?? null,
    media_count: d.media_count ?? null,
    retrieval_docs: d.retrieval_docs ?? null,
    media_assets: d.media_assets ?? null,
    intent_cluster: d.intent_cluster ?? null,
    created_at: d.created_at ?? new Date().toISOString(),
  };
}